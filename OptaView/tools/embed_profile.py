#!/usr/bin/env python3
"""Turns a profile JSON file into the header that builds it into the OptaView firmware.

    python3 OptaView/tools/embed_profile.py            # rewrite OptaViewBuiltinProfile.h
    python3 OptaView/tools/embed_profile.py --check    # fail if the header is out of date

The header is generated: edit profiles/sunsaver-mppt.json, then run this script. The host test
suite (tests/host/optaview) runs it with --check, so a stale header fails the pull request.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROFILE = os.path.join(HERE, "..", "profiles", "sunsaver-mppt.json")
HEADER = os.path.join(HERE, "..", "OptaViewBuiltinProfile.h")
DELIMITER = "OVPROFILE"
LINE_WIDTH = 110


def chunks(text, width):
    """Splits text into pieces no longer than width, never inside a UTF-8 sequence."""
    start = 0
    while start < len(text):
        yield text[start:start + width]
        start += width


def render(profile_path):
    with open(profile_path, "r", encoding="utf-8") as handle:
        source = handle.read()
    data = json.loads(source)
    # Minified: the firmware parses it at start-up, so every byte less is flash and heap saved.
    compact = json.dumps(data, separators=(",", ":"), ensure_ascii=True)
    if ")" + DELIMITER + '"' in compact:
        raise SystemExit("the profile contains the raw string delimiter; change DELIMITER")
    name = os.path.basename(profile_path)
    lines = [
        "/**",
        " * OptaViewBuiltinProfile.h",
        " *",
        " * GENERATED by tools/embed_profile.py from profiles/%s. Do not edit by hand:" % name,
        " * change the JSON file and run the script again.",
        " */",
        "",
        "#ifndef OPTAVIEW_BUILTIN_PROFILE_H",
        "#define OPTAVIEW_BUILTIN_PROFILE_H",
        "",
        "namespace optaview {",
        "",
        "// %s, version %s, %d registers" % (data.get("profile", "?"), data.get("version", "?"),
                                            len(data.get("registers", []))),
        "static const char OV_BUILTIN_PROFILE[] =",
    ]
    # One raw string literal per line; the compiler joins adjacent literals.
    for piece in chunks(compact, LINE_WIDTH):
        lines.append('    R"%s(%s)%s"' % (DELIMITER, piece, DELIMITER))
    lines[-1] += ";"
    lines += [
        "",
        "}  // namespace optaview",
        "",
        "#endif  // OPTAVIEW_BUILTIN_PROFILE_H",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    text = render(PROFILE)
    if check:
        try:
            with open(HEADER, "r", encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            print("OptaViewBuiltinProfile.h is out of date. Run: python3 OptaView/tools/embed_profile.py")
            return 1
        print("OptaViewBuiltinProfile.h matches profiles/sunsaver-mppt.json")
        return 0
    with open(HEADER, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d bytes)" % (os.path.normpath(HEADER), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
